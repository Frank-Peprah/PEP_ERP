// Bundle the API into a single Deno-compatible file for Supabase Edge Functions.
// Our own code is bundled; npm dependencies stay external as pinned npm: specifiers.
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';

const pkgVersion = (name) => JSON.parse(readFileSync(`node_modules/${name}/package.json`, 'utf8')).version;
const deps = ['fastify', '@fastify/cors', 'pg', 'decimal.js', 'jose'];
const map = Object.fromEntries(deps.map((d) => [d, `npm:${d}@${pkgVersion(d)}`]));

await build({
  entryPoints: ['supabase/functions/pep-api/entry.ts'],
  outfile: 'supabase/functions/pep-api/index.ts',
  bundle: true, format: 'esm', platform: 'node', target: 'es2022',
  alias: { '@pep/accounting-domain': './packages/accounting-domain/src/index.ts' },
  plugins: [{
    name: 'npm-specifiers',
    setup(b) {
      b.onResolve({ filter: /.*/ }, (a) => {
        if (map[a.path]) return { path: map[a.path], external: true };
        if (a.path.startsWith('node:')) return { path: a.path, external: true };
        return undefined;
      });
    },
  }],
  banner: { js: '// GENERATED by scripts/build-edge.mjs — do not edit.\nimport process from "node:process";\nimport { Buffer } from "node:buffer";' },
  legalComments: 'none',
});
console.log('built supabase/functions/pep-api/index.ts with', map);
